def _fail_row(reason: str, row: pd.Series, detail: str = "") -> dict:
    """Failure records carry the sop-uid-short, NEVER empi_anon (outputs/ is not ignored)."""
    return {"reason": reason, "view": row.get("view", ""), "contra_side": row.get("contra_side", ""),
            "split": row.get("split", ""), "laterality": row.get("laterality", ""),
            "sop_uid_short": uid_short(row["SOPInstanceUID_anon"]), "detail": detail}


def assert_out_dir_is_outside_repo(out_dir: Path) -> None:
    """Refuse to write shards anywhere inside this repository.

    DATA HYGIENE, safety-critical: the shard sidecar carries `empi_anon` and the FULL
    SOPInstanceUID_anon for every image, and each sample's .json member repeats them.
    `--out-dir outputs/shards` would therefore drop patient identifiers straight into a
    tracked directory. derived-data/ and metadata-files/ are git-ignored, but shards are
    tens of GB and do not belong in the project tree at all — Drive or a scratch disk is
    the right destination. Raises ValueError with the fix spelled out.
    """
    resolved = Path(out_dir).expanduser().resolve()
    root = Path(PROJECT_ROOT).resolve()
    if resolved == root or root in resolved.parents:
        raise ValueError(
            f"--out-dir {resolved} is INSIDE the repository ({root}). The shard sidecar and "
            f"every sample .json carry empi_anon and full SOP UIDs, so writing them there would "
            f"put patient identifiers in a tracked path. Point --out-dir at a location outside "
            f"the project (a Drive folder, an external disk, or a scratch directory).")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="DICOM -> contralateral-knee crop -> WebDataset shards (torch-free).")
    ap.add_argument("--config", default="config/feasibility.yaml")
    ap.add_argument("--dicom-root", required=True, help="root holding the transferred DICOM tree")
    ap.add_argument("--out-dir", default=None, help="directory the .tar shards are written to")
    ap.add_argument("--splits", default="train,val",
                    help="comma-separated splits to process; the sealed test split is EXCLUDED "
                         "by default and additionally requires --include-test")
    ap.add_argument("--include-test", action="store_true",
                    help="unseal the LOCKED test split (non-negotiable #4); logged loudly")
    ap.add_argument("--limit", type=int, default=None, help="process at most N images (smoke test)")
    ap.add_argument("--dry-run", action="store_true",
                    help="walk the manifest and report what WOULD be processed; reads no pixels")
    args = ap.parse_args(argv)

    cfg = load_config(args.config)
    log = setup_logging(cfg.path(cfg["paths"]["run_log"]))

    # ---- data-hygiene gate, checked FIRST so a bad --out-dir fails in milliseconds ----
    if args.out_dir:
        try:
            assert_out_dir_is_outside_repo(Path(args.out_dir).expanduser())
        except ValueError as exc:
            log.error("%s", exc)
            return 2

    # ---- input gate: a missing or empty DICOM root exits cleanly, no traceback ----
    dicom_root = Path(args.dicom_root).expanduser()
    if not dicom_root.exists() or not dicom_root.is_dir():
        log.error("DICOM root not found: %s", dicom_root)
        log.error("Nothing to preprocess. Transfer the DICOMs first (Track B: src.make_globus_batch "
                  "-> globus transfer), then re-run with --dicom-root pointing at that tree.")
        return 2
    suffix = str(cfg["transfer"]["dicom_suffix"])
    has_any = next(dicom_root.rglob(f"*{suffix}"), None)
    if has_any is None:
        log.error("DICOM root is EMPTY (no '*%s' under %s)", suffix, dicom_root)
        log.error("Nothing to preprocess. Transfer the DICOMs first (Track B: src.make_globus_batch "
                  "-> globus transfer), then re-run with --dicom-root pointing at that tree.")
        return 2

    splits = [s.strip() for s in str(args.splits).split(",") if s.strip()]
    assert splits, "--splits resolved to an empty list"
    bad = [s for s in splits if s not in ("train", "val", "test")]
    if bad:
        log.error("unknown split(s) %s; allowed: train, val, test", bad)
        return 2
    if "test" in splits and not args.include_test:
        log.error("REFUSING to process the LOCKED test split without --include-test "
                  "(success non-negotiable #4: the test set is read exactly once, after the "
                  "model, ensemble rule, thresholds and analysis script are frozen).")
        return 2
    if "test" in splits:
        log.warning("*** SEALED TEST SPLIT UNLOCKED via --include-test — this must happen ONCE, "
                    "after the model/ensemble/thresholds/analysis script are frozen and the crop "
                    "QA + laterality audit are signed off. ***")

    params = PreprocessParams.from_config(cfg)
    assert params.localizer == "intensity_profile", \
        f"only the intensity_profile localizer is implemented here, config says {params.localizer!r}"
    shard_cfg = cfg["preprocess"]["shards"]
    views_kept = list(cfg["preprocess"]["views_kept"])
    sidecar_columns = list(cfg["preprocess"]["sidecar_columns"])
    coh = cfg.path(cfg["paths"]["cohort_dir"])

    man = build_manifest(cfg, log)

    # The per-patient missing-view mask is a property of the COHORT, not of this run, so
    # it is computed from the FULL manifest BEFORE --splits/--limit narrow the work list.
    # Deriving it from a truncated work list would report n_views=1 for a patient whose
    # lateral and sunrise films simply were not scheduled, and that wrong mask would be
    # written into the shard the model reads.
    masks = view_masks(man, views_kept).set_index("empi_anon")

    work = man[man["split"].isin(splits)].sort_values(
        ["empi_anon", "view", "SOPInstanceUID_anon"], kind="mergesort").reset_index(drop=True)
    if args.limit is not None:
        work = work.head(int(args.limit)).reset_index(drop=True)
        log.warning("--limit %d: processing only the first %d scheduled images. n_views in the "
                    "sidecar remains the FULL-cohort mask; n_views_written will be smaller.",
                    int(args.limit), len(work))

    log.info("scheduled %d images / %d patients for splits=%s (test %s)",
             len(work), work["empi_anon"].nunique(), splits,
             "INCLUDED" if "test" in splits else "SEALED")
    for s in splits:
        sub = work[work["split"] == s]
        log.info("  split %-5s images=%d patients=%d views=%s", s, len(sub),
                 sub["empi_anon"].nunique(), sub["view"].value_counts().to_dict())
    log.info("  bilateral 'B' frontals needing half-select: %d; unilateral/other: %d",
             int(((work["view"] == "frontal") & (work["laterality"] == "B")).sum()),
             int(((work["view"] != "frontal") | (work["laterality"] != "B")).sum()))
    log.info("  horizontal_flip==1: %d; manifest inverted==1: %d",
             int((work["horizontal_flip"] == 1).sum()), int((work["inverted"] == 1).sum()))

    if args.dry_run:
        missing = 0
        for p in work["dicom_path"]:
            if not (dicom_root / str(p)).exists():
                missing += 1
        log.info("DRY RUN: no pixels read. %d/%d scheduled files present under %s (%d missing).",
                 len(work) - missing, len(work), dicom_root, missing)
        log.info("DRY RUN: would write shards named '%s' (<= %s MB) with sidecar '%s'.",
                 shard_cfg["name_pattern"], shard_cfg["max_shard_mb"], shard_cfg["sidecar_csv"])
        return 0

    if not args.out_dir:
        log.error("--out-dir is required unless --dry-run is used")
        return 2
    out_dir = Path(args.out_dir).expanduser()
    try:
        assert_out_dir_is_outside_repo(out_dir)
    except ValueError as exc:
        log.error("%s", exc)
        return 2
    out_dir.mkdir(parents=True, exist_ok=True)

    log.info("normalization: PER IMAGE robust clip at percentiles %s + min-max to [0,1]. "
             "No statistic is pooled across images, so nothing can leak across splits "
             "(non-negotiable #2) and nothing is persisted.", list(params.clip_percentiles))

    # A shorter re-run leaves higher-index shards from a previous, longer run behind; a
    # WebDataset glob would silently pick them up alongside the new ones.
    stale = sorted(p.name for s in splits for p in out_dir.glob(f"{s}-*.tar"))
    if stale:
        log.warning("%d pre-existing shard(s) in %s will be overwritten or ORPHANED: %s — delete "
                    "them before training if this run writes fewer shards", len(stale), out_dir,
                    ", ".join(stale[:10]) + (" ..." if len(stale) > 10 else ""))

    writers = {s: ShardWriter(out_dir, s, shard_cfg["name_pattern"], shard_cfg["max_shard_mb"])
               for s in splits}
    rows: list[dict] = []
    failures: list[dict] = []
    n_inverted_disagree = 0
    n_modality_lut_error = 0
    n_voi_lut_error = 0
    lut_error_examples: list[str] = []
    t0 = time.time()

    for i, row in enumerate(work.itertuples(index=False)):
        r = pd.Series(row._asdict())
        path = dicom_root / str(r["dicom_path"])
        # EVERYTHING per-image lives inside this try, key and record construction
        # included: a malformed time_from_landmark or empi_anon must route ONE image to
        # the failure report, not abort a 6,090-image run at image 5,000.
        try:
            if not path.exists():
                raise PreprocessError("file_not_found", "")
            arr, meta = read_dicom(path, params)
            if bool(meta["dicom_inverted"]) != bool(int(r["inverted"]) == 1):
                n_inverted_disagree += 1
            if meta.get("modality_lut_error"):
                n_modality_lut_error += 1
                if len(lut_error_examples) < 5:
                    lut_error_examples.append(f"modality_lut: {meta['modality_lut_error']}")
            if meta.get("voi_lut_error"):
                n_voi_lut_error += 1
                if len(lut_error_examples) < 5:
                    lut_error_examples.append(f"voi_lut: {meta['voi_lut_error']}")
            out, spec = crop_contralateral_knee(
                arr, view=str(r["view"]), laterality=str(r["laterality"]),
                contra_side=str(r["contra_side"]), horizontal_flip=int(r["horizontal_flip"]),
                params=params)

            key = sample_key(r["empi_anon"], spec.view, r["SOPInstanceUID_anon"])
            m = masks.loc[r["empi_anon"]]
            record = {
                "empi_anon": str(r["empi_anon"]),
                "sop_uid": str(r["SOPInstanceUID_anon"]),
                "view": spec.view,
                "contra_side": spec.contra_side,
                "split": str(r["split"]),
                "event_indicator": int(r["event_indicator"]),
                "time_from_landmark": int(r["time_from_landmark"]),
                "shard": "",
                "key": key,
                "crop_method": spec.crop_method,
                "crop_confidence": float(spec.crop_confidence),
                "masked_pct": float(spec.masked_pct),
                "sop_uid_short": uid_short(r["SOPInstanceUID_anon"]),
                "index_side": str(r["index_side"]),
                "laterality": str(r["laterality"]),
                "horizontal_flip": int(r["horizontal_flip"]),
                "inverted": int(r["inverted"]),
                "half_selected": spec.half_selected,
                "orientation": spec.orientation,
                "mirrored": bool(spec.mirrored),
                "out_size": int(params.out_size),
                **{f"has_{v}": bool(m[f"has_{v}"]) for v in views_kept},
                "n_views": int(m["n_views"]),
            }
            payload = {k: v for k, v in record.items() if k != "shard"}
            members = [(params.image_format, encode_image(out, params.image_format)),
                       ("json", json.dumps(payload, sort_keys=True).encode("utf-8"))]
        except PreprocessError as exc:
            failures.append(_fail_row(exc.reason, r, exc.detail))
            continue
        except Exception as exc:                      # never let one bad file kill the run
            failures.append(_fail_row("unexpected_error", r, f"{type(exc).__name__}: {exc}"))
            continue

        record["shard"] = writers[str(r["split"])].write(key, members)
        rows.append(record)
        if (i + 1) % 500 == 0:
            log.info("  processed %d/%d (%.1f img/s)", i + 1, len(work),
                     (i + 1) / max(1e-6, time.time() - t0))

    for wtr in writers.values():
        wtr.close()

    if not rows:
        log.error("no images were successfully processed (%d failures)", len(failures))
        _write_failures(cfg, failures, coh, log)
        return 1

    side = pd.DataFrame(rows)
    # Config-declared columns first, then the extras the training notebook needs.
    ordered = [c for c in sidecar_columns if c in side.columns]
    extras = [c for c in side.columns if c not in ordered]
    side = side[ordered + extras]

    written = view_masks(side, views_kept).set_index("empi_anon")
    n_written = written.rename(columns={f"has_{v}": f"w_{v}" for v in views_kept})
    side["n_views_written"] = side["empi_anon"].map(n_written["n_views"]).astype(int)
    drift = int((side["n_views"] != side["n_views_written"]).sum())
    if drift:
        log.warning("view-mask drift on %d rows: a scheduled view was lost to a decode failure; "
                    "group the sidecar by empi_anon for the authoritative mask", drift)
        failures.append({"reason": "view_mask_drift", "view": "", "contra_side": "", "split": "",
                         "laterality": "", "sop_uid_short": "", "detail": f"{drift} rows"})

    sidecar_path = out_dir / str(shard_cfg["sidecar_csv"])
    side.to_csv(sidecar_path, index=False)
    derived_copy = coh / f"preprocess_{shard_cfg['sidecar_csv']}"
    side.to_csv(derived_copy, index=False)

    fail_counts = pd.Series([f["reason"] for f in failures]).value_counts().to_dict() if failures else {}
    mp = side["masked_pct"].astype(float)
    run_json = {
        "out_dir": str(out_dir),
        "dicom_root": str(dicom_root),
        "splits": splits,
        "include_test": bool(args.include_test),
        "limit": int(args.limit) if args.limit is not None else None,
        "sidecar_csv": str(sidecar_path),
        "n_images_scheduled": int(len(work)),
        "n_images_written": int(len(side)),
        "n_patients_written": int(side["empi_anon"].nunique()),
        "n_failures": int(len(failures)),
        "failures_by_reason": {str(k): int(v) for k, v in fail_counts.items()},
        # protocol section 13 exclusions (these NEVER reach a shard)
        "n_excluded_excessive_masking": int(fail_counts.get(REASON_EXCESSIVE_MASKING, 0)),
        "n_excluded_localization_failed": int(fail_counts.get(REASON_LOCALIZATION_FAILED, 0)),
        "max_masked_pct": float(params.max_masked_pct),
        "border_band_fraction": round(border_band_fraction(params.out_size,
                                                           params.mask_border_frac), 4),
        "masked_pct": {
            "mean": round(float(mp.mean()), 4), "min": round(float(mp.min()), 4),
            "p50": round(float(mp.quantile(0.50)), 4), "p90": round(float(mp.quantile(0.90)), 4),
            "p99": round(float(mp.quantile(0.99)), 4), "max": round(float(mp.max()), 4),
            "n_gt_border_only": int((mp > border_band_fraction(params.out_size,
                                                               params.mask_border_frac) + 1e-9).sum()),
        },
        # fallback_rate is over WRITTEN crops and is 0 by construction while
        # exclude_failed_localization is on; localization_failure_rate is the real number.
        "fallback_rate": round(float((side["crop_method"] == "fallback_center").mean()), 4),
        "localization_failure_rate": round(
            float(fail_counts.get(REASON_LOCALIZATION_FAILED, 0))
            / max(1, len(side) + int(fail_counts.get(REASON_LOCALIZATION_FAILED, 0))), 4),
        # DICOM PhotometricInterpretation vs the manifest `inverted` flag. The DICOM tag
        # is authoritative; this count is a real QA number over the whole run.
        "n_inverted_disagree": int(n_inverted_disagree),
        "pct_inverted_disagree": round(100.0 * n_inverted_disagree / max(1, len(side)), 3),
        # LUT fallbacks are degradations, not failures — counted so they are never silent.
        "n_modality_lut_error": int(n_modality_lut_error),
        "n_voi_lut_error": int(n_voi_lut_error),
        "lut_error_examples": lut_error_examples,
        "shards": {s: writers[s].shards for s in splits},
        "params": {k: (list(v) if isinstance(v, tuple) else v) for k, v in asdict(params).items()},
        "written_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
    }
    (coh / "preprocess_run.json").write_text(json.dumps(run_json, indent=2))

    _write_failures(cfg, failures, coh, log)

    n_fb = int((side["crop_method"] == "fallback_center").sum())
    log.info("wrote %d samples / %d patients in %.1fs", len(side), side["empi_anon"].nunique(),
             time.time() - t0)
    for s in splits:
        sub = side[side["split"] == s]
        log.info("  split %-5s samples=%d shards=%d (%s)", s, len(sub), len(writers[s].shards),
                 ", ".join(writers[s].shards) or "none")
    n_loc_failed = int(fail_counts.get(REASON_LOCALIZATION_FAILED, 0))
    n_attempted = len(side) + n_loc_failed
    log.info("  crop_method fallback_center among WRITTEN crops: %d/%d (%.2f%%); mean "
             "crop_confidence %.3f. Localization-failure rate among crops that reached "
             "localization: %d/%d (%.2f%%) — with exclude_failed_localization=%s the written "
             "fallback count is 0 by construction, so the second number is the real one.",
             n_fb, len(side), 100.0 * n_fb / len(side), float(side["crop_confidence"].mean()),
             n_loc_failed, n_attempted, 100.0 * n_loc_failed / max(1, n_attempted),
             params.exclude_failed_localization)
    log.info("  half-select: %s", side["half_selected"].value_counts().to_dict())
    log.info("  orientation after standardize_to_left=%s: %s", params.standardize_to_left,
             side["orientation"].value_counts().to_dict())
    log.info("  masked_pct (protocol s13): mean %.4f  p50 %.4f  p90 %.4f  max %.4f  "
             "(border band alone %.4f, cap %.2f)", float(mp.mean()), float(mp.quantile(0.50)),
             float(mp.quantile(0.90)), float(mp.max()),
             border_band_fraction(params.out_size, params.mask_border_frac),
             params.max_masked_pct)
    log.info("  protocol s13 EXCLUSIONS (not written to any shard): excessive_masking=%d, "
             "localization_failed=%d (exclude_failed_localization=%s, min_crop_confidence=%.2f)",
             int(fail_counts.get(REASON_EXCESSIVE_MASKING, 0)),
             int(fail_counts.get(REASON_LOCALIZATION_FAILED, 0)),
             params.exclude_failed_localization, params.min_crop_confidence)
    log.info("  PhotometricInterpretation vs manifest 'inverted' disagreements: %d/%d (%.2f%%) "
             "(the DICOM tag is trusted; the manifest flag is reported only)",
             n_inverted_disagree, len(side), 100.0 * n_inverted_disagree / max(1, len(side)))
    if n_modality_lut_error or n_voi_lut_error:
        log.warning("  LUT fallbacks: modality-LUT %d, VOI-LUT %d (image kept, rescaled pixels "
                    "used). Examples: %s", n_modality_lut_error, n_voi_lut_error,
                    "; ".join(lut_error_examples) or "none")
    else:
        log.info("  LUT fallbacks: modality-LUT 0, VOI-LUT 0")
    log.info("  failures: %d %s", len(failures), fail_counts if failures else "{}")
    log.info("sidecar -> %s (copy: %s); run record -> %s", sidecar_path, derived_copy,
             coh / "preprocess_run.json")
    log.info("NEXT: python3 -m src.crop_qa  — training is BLOCKED until the crop QA sheet is signed.")
    return 0


def _write_failures(cfg, failures: list[dict], cohort_dir: Path, log: logging.Logger) -> None:
    """Failure reporting, split by data-hygiene tier.

    outputs/ is NOT git-ignored, so the configured fail_report_csv holds COUNTS BY
    REASON only (reason x view x contra_side x split). The row-level detail, keyed by
    sop_uid_short (never empi_anon, never a path), goes to git-ignored derived-data/.
    """
    cols = ["reason", "view", "contra_side", "split", "laterality", "sop_uid_short", "detail"]
    df = pd.DataFrame(failures, columns=cols) if failures else pd.DataFrame(columns=cols)

    path = cfg.path(cfg["preprocess"]["fail_report_csv"])
    path.parent.mkdir(parents=True, exist_ok=True)
    if len(df):
        agg = (df.groupby(["reason", "view", "contra_side", "split"], dropna=False)
                 .size().rename("n_images").reset_index()
                 .sort_values(["n_images", "reason"], ascending=[False, True]))
    else:
        agg = pd.DataFrame(columns=["reason", "view", "contra_side", "split", "n_images"])
    agg.to_csv(path, index=False)

    detail_path = cohort_dir / "preprocess_failures_detail.csv"
    detail_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(detail_path, index=False)
    log.info("failure report -> %s (%d aggregate rows, counts only); detail -> %s (%d rows, "
             "sop_uid_short only)", path, len(agg), detail_path, len(df))


