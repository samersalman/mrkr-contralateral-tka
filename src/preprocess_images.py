"""preprocess_images.py — DICOM -> CONTRALATERAL-knee 512x512 crop -> WebDataset shards.

Track C of the plan, torch-free. This module turns each pre-index radiograph of the
LOCKED 3,709-patient cohort into one 8-bit PNG that contains the CONTRALATERAL knee
(the knee that has NOT been replaced) and nothing else, then packs those PNGs into
WebDataset-compatible `.tar` shards with a per-image label sidecar.

Success non-negotiable #1 (protocol sections 14/23): the crop must contain the
contralateral knee, ZERO index-knee pixels, and ZERO burned-in laterality markers.
4,075 of the 4,269 frontal films are bilateral ('B' — BOTH knees on one image), so a
metadata-guided half-select is required and an inverted sign convention there would
silently train the model on the already-replaced knee. `contralateral_image_half`
is therefore written as a small pure function with the truth table in its docstring,
covered by tests/test_preprocess_images.py, and audited visually by src/crop_qa.py,
which BLOCKS training until a reviewer signs off.

Non-negotiable #2 (no leakage): intensity normalization is strictly PER IMAGE
(robust percentile clip + min-max). No statistic is pooled across images, so no
cross-split quantity exists to leak and none is persisted.

Non-negotiable #4 (sealed test): `--splits` defaults to `train,val`. Processing the
test split additionally requires the explicit `--include-test` flag and is logged
at WARNING level.

Protocol section 13 (masked pixels): every crop records `masked_pct` — the border band
that `mask_borders` unconditionally destroys PLUS the out-of-bounds padding that
`square_crop` had to invent — and a crop whose `masked_pct` exceeds
`preprocess.max_masked_pct`, or whose joint localization FAILED, is routed to the
failure report instead of into a shard. Nothing that a reviewer would call "mostly
blank" or "not actually localized" reaches the model.

Manifest composition (verified against the parquet on 2026-07-24; asserted in
`build_manifest`, so a silent upstream change fails loudly):
  6,122 selected images -> 6,090 kept after dropping 32 'E'/'I' rows (config views_kept)
  frontal 'F' 4,269 = 4,075 bilateral 'B' (half-select) + 194 unilateral
  lateral 'L' 1,659 + sunrise 'S' 162  -> already contralateral-side-only, no half-select
  horizontal_flip == 1 on 287 kept images; inverted == 1 on 1,476 kept images
  3,709 patients; kept rows by split: train 4,270 / val 602 / test 1,218

KNOWN LIMITATION — the two MRKR flags this module trusts are NOT equally trustworthy:
  * `inverted` is CROSS-CHECKED. Every decode reads the DICOM's own
    PhotometricInterpretation tag, and disagreements with the manifest flag are counted
    (`n_inverted_disagree` in preprocess_run.json). The DICOM tag wins; the manifest
    flag is reported only. A wrong `inverted` flag therefore cannot corrupt a crop.
  * `horizontal_flip` is NOT cross-checked and CANNOT BE. It is a MODEL-INFERRED MRKR
    annotation (generated by models trained on 6,000 annotated images, dataset caution
    B.4) with an UNQUANTIFIED error rate, and no DICOM tag records it. It drives
    half-select on 287 bilateral films: a false positive or false negative there hands
    the model the INDEX knee for that image. There is no automated defence — this is
    precisely why src.crop_qa renders the full film with the selected half outlined and
    blocks training until a human confirms the half-select on a real sample.

This module DEFINES THE CONTRACT that notebooks/preprocess_colab.ipynb (task T5) must
mirror byte-for-byte and that notebooks/train_colab.ipynb (task T7) reads. The public
functions below are the contract: keep them small, pure, and identically named.

Run:  python3 -m src.preprocess_images --dicom-root <DICOM root> --out-dir <shard dir>
      python3 -m src.preprocess_images --dicom-root <DICOM root> --dry-run
"""
